    /// VM-like: 4 CPUs, isolated 2-3 (full boot parameters), NO `numa_node`,
    /// NO PCIe link files, NO `node` directory, NO cpufreq, global hugepages
    /// only (1024 free), no IOMMU. NICs: `0000:00:03.0` virtio (0x1af4,
